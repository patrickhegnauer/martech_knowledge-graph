# CSV entry point -- fill in a spreadsheet instead of writing Python.
# One row per stage; journey/requirement/KPI/data-layer columns repeat
# the same value on every row.
# ---------------------------------------------------------------------------

import csv


def build_journey_from_csv(csv_path: str, xdm_base_url: str = DEFAULT_XDM_BASE_URL,
                           existing_components: dict = None) -> str:
    with open(csv_path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        raise ValueError("CSV has no data rows")

    first = rows[0]

    def yn(val):
        return str(val).strip().lower() in ("yes", "true", "1")

    def opt_float(val):
        return float(val) if val and val.strip() else None

    seen_components = {}
    components = []
    stages = []
    for row in rows:
        ckey = row["component_key"].strip()
        if ckey not in seen_components:
            spec = ComponentSpec(
                key=ckey,
                label=row["component_label"].strip(),
                component_type=row["component_type"].strip(),
                definition=row["component_definition"].strip(),
                caveats=row["component_caveats"].strip(),
                context=row["component_context"].strip(),
                owner=row["component_owner"].strip(),
                xdm_path=row["component_xdm_path"].strip(),
            )
            seen_components[ckey] = spec
            components.append(spec)

        stages.append(StageSpec(
            key=row["stage_key"].strip(),
            label=row["stage_label"].strip(),
            order=int(row["stage_order"]),
            component_key=ckey,
            filter_value=row.get("filter_value", "").strip() or None,
            rolls_up_to_kpi=yn(row.get("rolls_up_to_kpi", "")),
        ))

    spec = JourneySpec(
        slug=first["journey_slug"].strip(),
        journey_label=first["journey_label"].strip(),
        journey_owner=first.get("journey_owner", "").strip() or None,
        requirement_label=first["requirement_label"].strip(),
        requirement_comment=first["requirement_comment"].strip(),
        kpi_label=first["kpi_label"].strip(),
        kpi_formula=first["kpi_formula"].strip(),
        kpi_owner=first["kpi_owner"].strip(),
        kpi_target=opt_float(first.get("kpi_target", "")),
        kpi_comment=first.get("kpi_comment", "").strip() or None,
        components=components,
        stages=stages,
        data_layer_variable=first.get("data_layer_variable", "").strip() or None,
        data_layer_source_system=first.get("data_layer_source_system", "").strip() or "Web data layer (digitalData)",
    )
    return build_journey_turtle(spec, xdm_base_url=xdm_base_url, existing_components=existing_components)


CSV_COLUMNS = [
    "journey_slug", "journey_label", "journey_owner",
    "requirement_label", "requirement_comment",
    "kpi_label", "kpi_formula", "kpi_owner", "kpi_target", "kpi_comment",
    "stage_key", "stage_label", "stage_order", "rolls_up_to_kpi",
    "component_key", "component_label", "component_type",
    "component_definition", "component_caveats", "component_context",
    "component_owner", "component_xdm_path", "filter_value",
    "data_layer_variable", "data_layer_source_system",
]


def write_csv_template(path: str):
    """Write an empty template CSV with the right headers, ready to fill in."""
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=CSV_COLUMNS)
        writer.writeheader()


