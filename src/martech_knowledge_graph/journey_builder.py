"""
Journey builder — describe a journey as structured Python, get correct
turtle out. Doesn't decide content for you (requirement wording, KPI
formulas, component definitions still need a human/judgment call) --
it just guarantees the RDF syntax is right and handles the fiddly
n-ary Measurement logic automatically.

Usage: see build_example_ecommerce() / build_example_login() at the
bottom for two worked examples that reproduce the existing files.
"""

import re
from dataclasses import dataclass, field


ONTOLOGY_NS = "https://example.org/martech/ontology/"

# Prefix for generated Component refs (Component.xdm_path gets appended to this).
# Org-specific -- overridable per call; server.py's /api/journeys/generate reads
# the persisted per-workspace setting (.mkg-settings.json) and passes it through.
DEFAULT_XDM_BASE_URL = "https://sandbox/SANDBOX_NAME/xdm/"


@dataclass
class ComponentSpec:
    key: str                 # short internal key, e.g. "product_views" -- used to link stages to this component
    label: str
    component_type: str      # "metric" | "dimension"
    definition: str
    caveats: str
    context: str
    owner: str
    xdm_path: str            # e.g. "commerce.productViews.value" -- becomes the refs URI
    refs: list = None        # full ref URIs; when set they are emitted verbatim instead of xdm_base_url + xdm_path


@dataclass
class StageSpec:
    key: str
    label: str
    order: int
    component_key: str       # which ComponentSpec.key measures this stage
    filter_value: str = None # only needed when multiple stages share one component
    rolls_up_to_kpi: bool = False


@dataclass
class JourneySpec:
    slug: str                # used for the data namespace and the output filename
    journey_label: str
    requirement_label: str
    requirement_comment: str
    kpi_label: str
    kpi_formula: str
    kpi_owner: str
    kpi_target: float = None
    kpi_comment: str = None
    journey_owner: str = None
    components: list = field(default_factory=list)   # list[ComponentSpec]
    stages: list = field(default_factory=list)        # list[StageSpec]
    data_layer_variable: str = None
    data_layer_source_system: str = "Web data layer (digitalData)"


def _esc(s):
    """Make a value safe inside a turtle string literal (double quotes become single quotes)."""
    return (s.replace("\\", "\\\\").replace('"', "'")
            .replace("\r\n", "\n").replace("\n", "\\n").replace("\r", "\\n").replace("\t", " "))


def slugify(text, fallback="item"):
    return re.sub(r"[^a-z0-9]+", "_", (text or "").lower()).strip("_") or fallback


def build_journey_turtle(spec: JourneySpec, xdm_base_url: str = DEFAULT_XDM_BASE_URL,
                         existing_components: dict = None) -> str:
    """existing_components maps component key -> URI of a component already defined elsewhere in the
    workspace; those are referenced instead of redefined, so their curated context is kept."""
    existing_components = existing_components or {}

    def comp_ref(key):
        return f"<{existing_components[key]}>" if key in existing_components else f"data:component_{key}"

    data_ns = f"https://example.org/martech/data/{spec.slug}/"
    lines = [
        f"# ==========================================================================",
        f"# {spec.journey_label} — instance data",
        f"# Generated by journey_builder.py -- conforms to martech-ontology.ttl",
        f"# ==========================================================================",
        "",
        f'@prefix martech: <{ONTOLOGY_NS}> .',
        f'@prefix data:    <{data_ns}> .',
        '@prefix rdfs:    <http://www.w3.org/2000/01/rdf-schema#> .',
        "",
        "# --------------------------------------------------------------------------",
        "# Requirement",
        "# --------------------------------------------------------------------------",
        "",
        "data:req a martech:Requirement ;",
        f'    rdfs:label "{_esc(spec.requirement_label)}" ;',
        f'    rdfs:comment "{_esc(spec.requirement_comment)}" ;',
        '    martech:status "active" ;',
        "    martech:addressed_by data:kpi .",
        "",
        "# --------------------------------------------------------------------------",
        "# KPI",
        "# --------------------------------------------------------------------------",
        "",
        "data:kpi a martech:KPI ;",
        f'    rdfs:label "{_esc(spec.kpi_label)}" ;',
        f'    martech:formula "{_esc(spec.kpi_formula)}" ;',
        f'    martech:owner "{_esc(spec.kpi_owner)}" ;',
    ]
    kpi_tail = "."
    if spec.kpi_target is not None:
        lines.append(f"    martech:target {spec.kpi_target} ;")
    if spec.kpi_comment:
        lines.append(f'    rdfs:comment "{_esc(spec.kpi_comment)}" {kpi_tail}')
    else:
        # close the last line with a period instead of semicolon
        lines[-1] = lines[-1].rstrip(" ;") + " ."
    lines.append("")

    journey_lines = [
        "data:journey a martech:Journey ;",
        f'    rdfs:label "{_esc(spec.journey_label)}" ;',
    ]
    if spec.journey_owner:
        journey_lines.append(f'    martech:owner "{_esc(spec.journey_owner)}" ;')
    journey_lines.append(
        "    martech:has_stage " + ", ".join(f"data:stage_{s.key}" for s in spec.stages) + " ."
    )

    lines += [
        "# --------------------------------------------------------------------------",
        "# Journey",
        "# --------------------------------------------------------------------------",
        "",
        *journey_lines,
        "",
        "# --------------------------------------------------------------------------",
        "# Stages",
        "# --------------------------------------------------------------------------",
        "",
    ]

    for s in spec.stages:
        block = [f"data:stage_{s.key} a martech:Stage ;", f'    rdfs:label "{_esc(s.label)}" ;']
        if s.rolls_up_to_kpi:
            block.append(f"    martech:order {s.order} ;")
            block.append("    martech:rolls_up_to data:kpi .")
        else:
            block.append(f"    martech:order {s.order} .")
        lines += block + [""]

    lines += [
        "# --------------------------------------------------------------------------",
        "# Components",
        "# --------------------------------------------------------------------------",
        "",
    ]
    for c in spec.components:
        if c.key in existing_components:
            continue
        lines += [
            f"data:component_{c.key} a martech:Component ;",
            f'    rdfs:label "{_esc(c.label)}" ;',
            f'    martech:component_type "{c.component_type}" ;',
            f'    martech:definition "{_esc(c.definition)}" ;',
            f'    martech:caveats "{_esc(c.caveats)}" ;',
            f'    martech:context "{_esc(c.context)}" ;',
            f'    martech:owner "{_esc(c.owner)}" ;',
            "    martech:refs " + (", ".join(f"<{r}>" for r in c.refs) if c.refs else f"<{xdm_base_url}{c.xdm_path}>") + " .",
            "",
        ]

    if spec.data_layer_variable:
        used_component_keys = sorted({s.component_key for s in spec.stages})
        lines += [
            "# --------------------------------------------------------------------------",
            "# Data layer variable",
            "# --------------------------------------------------------------------------",
            "",
            "data:dlv a martech:DataLayerVariable ;",
            f'    rdfs:label "{_esc(spec.data_layer_variable)}" ;',
            f'    martech:source_system "{_esc(spec.data_layer_source_system)}" ;',
            "    martech:maps_to " + ", ".join(comp_ref(k) for k in used_component_keys) + " .",
            "",
        ]

    lines += [
        "# --------------------------------------------------------------------------",
        "# Measurements",
        "# --------------------------------------------------------------------------",
        "",
    ]
    for s in spec.stages:
        block = [
            f"data:measurement_{s.key} a martech:Measurement ;",
            f"    martech:measured_entity data:stage_{s.key} ;",
        ]
        if s.filter_value:
            block.append(f"    martech:measured_component {comp_ref(s.component_key)} ;")
            block.append(f'    martech:filter_value "{_esc(s.filter_value)}" .')
        else:
            block.append(f"    martech:measured_component {comp_ref(s.component_key)} .")
        lines += block + [""]

    return "\n".join(lines).rstrip() + "\n"


# ---------------------------------------------------------------------------
# Reverse direction -- read a journey file back into a JourneySpec so a form
# can edit it. Refuses anything it could not write back unchanged.
# ---------------------------------------------------------------------------

_ROUND_TRIP_PREDICATES = {
    "type", "label", "comment", "status", "addressed_by", "formula", "owner", "target", "has_stage", "order",
    "rolls_up_to", "component_type", "definition", "caveats", "context", "refs", "maps_to", "source_system",
    "measured_entity", "measured_component", "filter_value",
}
_ROUND_TRIP_TYPES = {"Requirement", "KPI", "Journey", "Stage", "Component", "DataLayerVariable", "Measurement"}


def _local(uri):
    return str(uri).rstrip("/").split("/")[-1].split("#")[-1]


def journey_from_graph(g, slug):
    """Returns (JourneySpec, None) or (None, reason). g must hold just this journey's file."""
    from rdflib import RDF, RDFS, Namespace
    M = Namespace(ONTOLOGY_NS)

    def one(node, pred):
        return g.value(node, pred)

    def text(node, pred, default=""):
        v = one(node, pred)
        return str(v) if v is not None else default

    for s, p, o in g:
        if p == RDF.type:
            name = _local(o)
            if name not in _ROUND_TRIP_TYPES:
                return None, f"contains a {name}, which the form cannot preserve"
        elif p == RDFS.label:
            continue
        elif p == RDFS.comment:
            continue
        elif _local(p) not in _ROUND_TRIP_PREDICATES or not str(p).startswith(ONTOLOGY_NS):
            return None, f"uses a property the form cannot preserve ({_local(p)})"

    journeys = list(g.subjects(RDF.type, M.Journey))
    kpis = list(g.subjects(RDF.type, M.KPI))
    reqs = list(g.subjects(RDF.type, M.Requirement))
    if len(journeys) != 1 or len(kpis) != 1 or len(reqs) != 1:
        return None, "must contain exactly one journey, one requirement and one KPI"
    journey, kpi, req = journeys[0], kpis[0], reqs[0]

    own_components = {}
    for c in g.subjects(RDF.type, M.Component):
        key = _local(c)[len("component_"):] if _local(c).startswith("component_") else _local(c)
        own_components[c] = ComponentSpec(
            key=key, label=text(c, RDFS.label), component_type=text(c, M.component_type),
            definition=text(c, M.definition), caveats=text(c, M.caveats), context=text(c, M.context),
            owner=text(c, M.owner), xdm_path="", refs=sorted(str(r) for r in g.objects(c, M.refs)),
        )

    measurements = {}
    for m in g.subjects(RDF.type, M.Measurement):
        stage = one(m, M.measured_entity)
        if stage in measurements:
            return None, "a stage is measured by more than one component"
        measurements[stage] = m

    stages = []
    for st in g.objects(journey, M.has_stage):
        m = measurements.get(st)
        comp = one(m, M.measured_component) if m is not None else None
        if comp is None:
            return None, f"stage '{text(st, RDFS.label)}' has no measured component"
        comp_key = own_components[comp].key if comp in own_components else (
            _local(comp)[len("component_"):] if _local(comp).startswith("component_") else _local(comp))
        name = _local(st)
        stages.append(StageSpec(
            key=name[len("stage_"):] if name.startswith("stage_") else name,
            label=text(st, RDFS.label), order=int(one(st, M.order) or 0), component_key=comp_key,
            filter_value=text(m, M.filter_value) or None, rolls_up_to_kpi=one(st, M.rolls_up_to) is not None,
        ))
    stages.sort(key=lambda s: s.order)

    dlvs = list(g.subjects(RDF.type, M.DataLayerVariable))
    if len(dlvs) > 1:
        return None, "contains more than one data layer variable"
    target = one(kpi, M.target)

    spec = JourneySpec(
        slug=slug, journey_label=text(journey, RDFS.label), journey_owner=text(journey, M.owner) or None,
        requirement_label=text(req, RDFS.label), requirement_comment=text(req, RDFS.comment),
        kpi_label=text(kpi, RDFS.label), kpi_formula=text(kpi, M.formula), kpi_owner=text(kpi, M.owner),
        kpi_target=float(target) if target is not None else None, kpi_comment=text(kpi, RDFS.comment) or None,
        components=list(own_components.values()), stages=stages,
        data_layer_variable=text(dlvs[0], RDFS.label) if dlvs else None,
        data_layer_source_system=(text(dlvs[0], M.source_system) if dlvs else "") or "Web data layer (digitalData)",
    )
    return spec, None


