def build_example_ecommerce() -> JourneySpec:
    components = [
        ComponentSpec("product_views", "Product views", "metric",
            "Number of times a product detail page was viewed.",
            "Counts page views, not unique visitors — a visitor viewing the same product twice counts twice.",
            "Entry point for the purchase funnel; used to benchmark top-of-funnel demand.",
            "Digital Analytics", "commerce.productViews.value"),
        ComponentSpec("product_list_adds", "Product list adds", "metric",
            "Number of times a product was added to the cart.",
            "Does not deduplicate repeated adds of the same product within one session.",
            "First explicit purchase-intent signal in the funnel.",
            "Digital Analytics", "commerce.productListAdds.value"),
        ComponentSpec("checkouts", "Checkouts", "metric",
            "Number of times a user started the checkout process.",
            "Counts checkout starts, not completions — a user can start checkout multiple times without purchasing.",
            "Marks the transition from browsing to transactional intent.",
            "Digital Analytics", "commerce.checkouts.value"),
        ComponentSpec("orders", "Orders", "metric",
            "Number of completed purchase orders.",
            "Includes orders later cancelled or refunded — not net of returns.",
            "The funnel's terminal event and the numerator of the order conversion rate KPI.",
            "Digital Analytics", "orders"),
    ]
    stages = [
        StageSpec("product_view", "Product view", 1, "product_views"),
        StageSpec("cart_add", "Cart add", 2, "product_list_adds"),
        StageSpec("checkout", "Checkout", 3, "checkouts"),
        StageSpec("order", "Order", 4, "orders", rolls_up_to_kpi=True),
    ]
    return JourneySpec(
        slug="ecommerce",
        journey_label="Ecommerce purchase journey",
        requirement_label="Understand shop performance and drop-off",
        requirement_comment="We want to understand how our shop is performing, and where in the journey people drop off.",
        kpi_label="Order conversion rate",
        kpi_formula="Orders / Product Views",
        kpi_owner="Ecommerce / Digital Marketing",
        kpi_target=0.0020,
        kpi_comment="Current value (2026): 0.11%. Target: 0.20% (illustrative example, not a real commitment).",
        journey_owner="Digital Marketing",
        components=components,
        stages=stages,
        data_layer_variable="digitalData.conversion.conversionFunnel.step",
    )


def build_example_login() -> JourneySpec:
    components = [
        ComponentSpec("page_name", "Page name", "dimension",
            "The page name/path captured on each page view; used here to identify funnel steps by value.",
            "A shared, general-purpose dimension — filtering by value (e.g. /customer/login) is required to isolate a specific journey step. The raw component alone doesn't identify a stage.",
            "A general-purpose dimension, likely reused by other journeys in a real implementation — filtering by value is what distinguishes each specific use, not the component itself.",
            "Digital Analytics", "web.webPageDetails.name"),
    ]
    stages = [
        StageSpec("login", "Login", 1, "page_name", filter_value="/customer/login"),
        StageSpec("login_success", "Login success", 2, "page_name", filter_value="/customer/login/success", rolls_up_to_kpi=True),
    ]
    return JourneySpec(
        slug="login",
        journey_label="Customer login journey",
        requirement_label="Understand monthly login frequency",
        requirement_comment="We want to know how many logins we have monthly (MAU), and how that compares to overall sessions.",
        kpi_label="Monthly login rate",
        kpi_formula="Monthly logins / Sessions",
        kpi_owner="Product Analytics",
        kpi_target=0.35,
        kpi_comment="Target: 35% of monthly sessions include a login (illustrative example, not a real commitment).",
        journey_owner="Product Analytics",
        components=components,
        stages=stages,
        data_layer_variable="digitalData.page.pageInfo.name",
    )


if __name__ == "__main__":
    print(build_journey_turtle(build_example_ecommerce()))
